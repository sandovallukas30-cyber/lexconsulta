// Catálogo de normas que fijan plazos en la legislación chilena indexada en
// Prima Lex — transcrito desde el informe de investigación "Plazos en la
// legislación chilena indexada en Prima Lex" (24 cuerpos legales revisados,
// artículo por artículo verificado contra el texto vigente). Es la base de
// datos de la entrada "Buscar por norma" de la Calculadora de Plazos: en vez
// de que la persona adivine si su plazo es de días hábiles o corridos, elige
// la norma concreta y el sistema ya sabe qué régimen, duración y efecto le
// corresponden.
//
// Los campos que el propio informe NO afirmó explícitamente para una norma
// puntual (fatalidad, régimen exacto de cómputo cuando el artículo no lo
// declara) quedan como `undefined`/con una nota de cautela en vez de
// inventarse — mejor "no verificado" que un dato falso con apariencia de
// certeza.

