export type UnidadPlazoNorma = UnidadPlazo

/** Clasificación funcional del plazo, no solo su origen formal. */
export type TipoPlazoNorma = 'sustantivo' | 'procesal' | 'administrativo' | 'convencional'

export interface NormaPlazo {
  id: string
  codigo: CodigoTipo
  /** Nombre corto del cuerpo legal para mostrar (coincide con nombreCorto en
   *  useStore, pero se repite acá para no acoplar este archivo al store). */
  nombreCodigo: string
  articulo: string
  materia: string
  cantidad: number
  /** Solo cuando el informe registra una "ventana" (mínimo y máximo) o un
   *  segundo plazo relevante (p.ej. el tope objetivo de un plazo dual). */
  cantidadMax?: number
  unidad: UnidadPlazoNorma
  regimen: RegimenComputo
  /** true/false solo cuando el informe lo afirma expresamente; undefined =
   *  no verificado para esta norma puntual. */
  fatal?: boolean
  tipo: TipoPlazoNorma
  diesAQuo: string
  efecto: string
  notas?: string
}

