/** Coincide si CADA palabra del query (>1 carácter) aparece en algún lugar
 *  del texto buscable, sin importar el orden -- así "SII liquidar" encuentra
 *  una materia como "Plazo del SII para liquidar..." aunque las palabras no
 *  queden una junto a la otra (mismo criterio que el buscador de artículos
 *  del Explorador). */
export function buscarNormasPlazo(query: string): NormaPlazo[] {
  const palabras = query.trim().toLowerCase().split(/\s+/).filter((w) => w.length > 1)
  if (palabras.length === 0) return CATALOGO_PLAZOS
  return CATALOGO_PLAZOS.filter((n) => {
    const texto = `${n.articulo} ${n.materia} ${n.nombreCodigo} ${n.notas ?? ''} ${n.diesAQuo} ${n.efecto}`.toLowerCase()
    return palabras.every((w) => texto.includes(w))
  })
}
