/** Refleja una lista de puntos «x,y …» respecto del eje vertical x = 50. */
export function reflejar(puntos: string): string {
  return puntos
    .trim()
    .split(/\s+/)
    .map((par) => {
      const [x, y] = par.split(',')
      return `${100 - Number(x)},${y}`
    })
    .join(' ')
}
